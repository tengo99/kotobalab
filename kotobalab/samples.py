def sample_question(level: str, area: str, topic: str) -> Question:
    prompt, options, explanation, distractors = SAMPLES[(level, area)]
    option_explanations = distractors.copy()
    option_explanations[0] = explanation
    return Question(level=level, area=area, topic=topic.strip(), prompt=prompt,
                    options=options.copy(), answer=1, explanation=explanation,
                    option_explanations=option_explanations)
